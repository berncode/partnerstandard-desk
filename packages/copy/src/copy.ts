/** "Reseller" reads "reseller"; a word with capitals inside ("OEM", "IPaaS") keeps them. */
function plainType(typeLabel: string): string {
  return typeLabel.replace(/\p{L}+/gu, (word) => (/^\p{Lu}\p{Ll}*$/u.test(word) ? word.toLowerCase() : word));
}

/** The label of the partner type Other, as PARTNER_TYPE_LABELS has it. It reads "partner" in a sentence. */
const OTHER_LABEL = 'Other';

/** The type as a noun after "your": "reseller", "OEM partner"; "partner" for Other. */
function typeNoun(typeLabel: string): string {
  return typeLabel === OTHER_LABEL ? 'partner' : plainType(typeLabel);
}

/** The type with its article, as partnerTypePhrase does: "a reseller", "an OEM partner"; "a partner" for Other. */
export function typeWithArticle(typeLabel: string): string {
  const noun = typeNoun(typeLabel);
  return `${/^[aeiou]/i.test(noun) ? 'an' : 'a'} ${noun}`;
}

